/**
 * The schema, in both dialects.
 *
 * Kept apart from db.js because DDL is the one place the two engines genuinely
 * differ — identity columns, full-text search and the absence of `rowid` in
 * Postgres — while every statement in db.js is written once and translated.
 *
 * The shape is deliberate: the job corpus is shared, because a posting is the
 * same posting whoever fetched it and re-scraping it per account would multiply
 * the load on Workana for no gain. Everything that differs per person lives in
 * `users` and `user_jobs` — their Workana session, their browser state, whether
 * *they* bid, whether the client contacted *them*, their stars and notes.
 */
import { isPostgres } from './sql.js';

/*
 * Column types, per engine.
 *
 * Booleans stay integers on Postgres rather than becoming BOOLEAN: the upserts
 * make flags sticky with GREATEST(old, new), which is arithmetic, and the JSON
 * the API returns has always carried 0 and 1. Changing that would ripple into
 * the front end for no benefit.
 */
const T = isPostgres
  ? {
      id: 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
      seq: 'BIGINT GENERATED BY DEFAULT AS IDENTITY',
      text: 'TEXT',
      int: 'INTEGER',
      real: 'DOUBLE PRECISION',
      json: 'TEXT',
    }
  : {
      id: 'INTEGER PRIMARY KEY AUTOINCREMENT',
      seq: 'INTEGER',
      text: 'TEXT',
      int: 'INTEGER',
      real: 'REAL',
      json: 'TEXT',
    };

