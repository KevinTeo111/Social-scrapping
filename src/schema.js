/*
 * Full-text search is the one feature with no common spelling.
 *
 * SQLite gets an FTS5 virtual table kept in step by reindex(). Postgres has the
 * capability built into the row itself: a generated tsvector column plus a GIN
 * index needs no maintenance at all, so on Postgres reindex() is a no-op.
 */
export const SEARCH = isPostgres
  ? `
ALTER TABLE jobs ADD COLUMN IF NOT EXISTS search tsvector
  GENERATED ALWAYS AS (
    to_tsvector('simple',
      coalesce(title, '') || ' ' || coalesce(summary, '') || ' ' ||
      coalesce(description, '') || ' ' || coalesce(skills, ''))
  ) STORED;
CREATE INDEX IF NOT EXISTS idx_jobs_search ON jobs USING GIN (search);
`
  : `
CREATE VIRTUAL TABLE IF NOT EXISTS jobs_fts USING fts5(
  slug UNINDEXED, title, summary, description, skills, client,
  tokenize = 'unicode61 remove_diacritics 2'
);
`;

/*
 * Indexes over columns that an older database may not have yet. These cannot sit
 * in TABLES: on an existing database that statement runs before the ALTERs
 * below, and indexing a column that is about to be added fails the whole
 * migration with "no such column".
 */
export const LATE_INDEXES = `
CREATE INDEX IF NOT EXISTS idx_jobs_seq ON jobs(seq);
CREATE INDEX IF NOT EXISTS idx_jobs_listed ON jobs(last_listed_at);
`;

